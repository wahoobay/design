import { cp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export async function build(root = process.cwd()) {
  const dist = join(root, 'dist');
  await rm(dist, { recursive: true, force: true });
  await mkdir(join(dist, 'logo'), { recursive: true });
  for (const name of await readdir(join(root, 'brand'))) {
    if (name.endsWith('.svg')) {
      await cp(join(root, 'brand', name), join(dist, 'logo', name));
    }
  }
  await writeFile(join(dist, 'tokens.css'), tokensCss(JSON.parse(await readFile(join(root, 'tokens', 'tokens.json'), 'utf8'))));
  await mkdir(join(dist, 'fonts'), { recursive: true });
  for (const { file } of FONT_SUBSETS) {
    await cp(join(root, 'node_modules', '@fontsource-variable', 'manrope', 'files', file), join(dist, 'fonts', file));
  }
  await writeFile(join(dist, 'fonts.css'), fontsCss());
  const css = [await readFile(join(root, 'src', 'base.css'), 'utf8')];
  for (const name of COMPONENT_FILES) css.push(await readFile(join(root, 'src', 'components', `${name}.css`), 'utf8'));
  await writeFile(join(dist, 'components.css'), `${COMPONENTS_HEADER}\n${css.join('\n')}`);
  await cp(join(root, 'src', 'docs', 'media'), join(dist, 'media'), { recursive: true });
  const docs = await readFile(join(root, 'src', 'docs', 'index.html'), 'utf8');
  await writeFile(join(dist, 'index.html'), inlineLogo(docs, await readFile(join(root, 'brand', 'wahoobay-logo.svg'), 'utf8')));
}

// Appended to base.css in this order.
const COMPONENT_FILES = ['nav', 'button', 'live', 'chip', 'tile', 'panel', 'card', 'chart', 'detect', 'form', 'footer', 'layout'];

// Replaces each <!-- @wb-logo --> with the logo's <svg>, so it follows currentColor; each copy gets its own ids.
function inlineLogo(page, logo) {
  const svg = logo.slice(logo.indexOf('<svg')).trim();
  let n = 0;
  return page.replaceAll('<!-- @wb-logo -->', () => {
    n += 1;
    return svg.replace(/\b(id|aria-labelledby)="([^"]+)"/g, (_, attr, id) => `${attr}="${id}-${n}"`);
  });
}

// Unicode ranges copied from @fontsource-variable/manrope index.css for the shipped subsets.
const FONT_SUBSETS = [
  { file: 'manrope-latin-ext-wght-normal.woff2', range: 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF' },
  { file: 'manrope-latin-wght-normal.woff2', range: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD' },
];

const COMPONENTS_HEADER = '/* Wahoo Bay components — generated by scripts/build.mjs from src/*.css. Do not edit by hand. */';

function fontsCss() {
  const faces = FONT_SUBSETS.map(({ file, range }) => `@font-face {
  font-family: "Manrope Variable";
  font-style: normal;
  font-weight: 200 800;
  font-display: swap;
  src: url("./fonts/${file}") format("woff2-variations");
  unicode-range: ${range};
}`);
  return `/* Wahoo Bay fonts — self-hosted Manrope (variable), generated by scripts/build.mjs. Do not edit by hand. */\n${faces.join('\n')}\n`;
}

const HEADER = '/* Wahoo Bay design tokens — generated from tokens/tokens.json; values from docs/superpowers/specs/2026-10-29-wahoobay-net-overhaul-design.md §4.3 (wahoobay/infra). Do not edit by hand. */';

const decls = (prefix, map) => Object.entries(map).map(([k, v]) => `  --wb-${prefix}${k}: ${v};`);

function tokensCss(t) {
  const radius = Object.entries(t.radius).map(([k, v]) => `  --wb-radius${k === 'default' ? '' : `-${k}`}: ${v};`);
  const light = [
    ...decls('color-', t.color.light),
    ...decls('font-', t.font),
    ...decls('text-', t.text),
    ...decls('space-', t.space),
    ...radius,
    `  --wb-shadow: ${t.shadow};`,
    `  --wb-measure: ${t.measure};`,
  ];
  return `${HEADER}\n:root {\n${light.join('\n')}\n}\n[data-theme="dark"] {\n${decls('color-', t.color.dark).join('\n')}\n}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await build();
}
